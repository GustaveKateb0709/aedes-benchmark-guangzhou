#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
Experiment 2: double/debiased machine learning (DML) on a system
with a KNOWN data-generating mechanism (methodological validation).
======================================================================
The simulated Breteau index (BI) is generated by the PFI mechanistic model,
in which week-t BI depends ONLY on week-t weather and a grid-specific
urbanisation scale.  Ground truth is therefore known exactly:

  * contemporaneous rainfall/temperature -> positive marginal effect equal
    to the mean PFI derivative (computable per observation);
  * lagged (1-6 week) rainfall/temperature -> ZERO true effect;
  * the rainfall response saturates (PFI brood factor) and the temperature
    response is non-monotone (Briere-type), both recoverable in shape.

A valid causal estimator must (i) return a positive contemporaneous effect,
(ii) shrink spurious lagged associations (weather autocorrelation +
seasonality) to zero after partialling out confounders, and (iii) reproduce
the non-linear dose-response shape.

Implementation: partially-linear DML (Chernozhukov et al., 2018) with
XGBoost nuisance learners, 5-fold cross-fitting repeated over 5 random
splits (median estimate, as recommended), cluster-robust (grid) and HC1
standard errors; naive unadjusted OLS as the confounded contrast.  The
dose-response is estimated by residualising a piecewise-linear spline basis
of the treatment (an 'FWL spline DML'), which is far more stable than
stratified ATEs in narrow bins.

Honest framing: this is a methodological validation on a
known-mechanism system, NOT a discovery of real-world causal effects.
"""
import os, sys
import numpy as np
import pandas as pd

BASE = os.path.dirname(os.path.abspath(__file__))
def _find_baseline_dir():
    """Resolve the baseline pipeline directory (panel data + features):
    the BASELINE_DIR environment variable, or the package root of this
    self-contained code-and-data package."""
    cands = [os.environ.get('BASELINE_DIR', ''),
             os.path.abspath(os.path.join(BASE, '..'))]      # this package
    for c in cands:
        if c and os.path.exists(os.path.join(c, 'results', 'panel_data.csv')):
            return c
    raise FileNotFoundError('panel_data.csv not found; set BASELINE_DIR')


BASELINE_DIR = _find_baseline_dir()
RES_A = os.path.abspath(os.path.join(BASE, '..', 'results'))
os.makedirs(RES_A, exist_ok=True)
sys.path.insert(0, BASELINE_DIR)
import pipeline as base  # renamed from pipeline_redo during repo unification   # PFI parameter constants + feature engineering

SEED = 2024
LAGS = range(0, 7)
K_FOLDS = 5
N_SPLIT_REPS = 5


# ------------------------------------------------------- ground truth -------
def truth_marginal_effects(panel):
    """Exact per-observation marginal effects recovered from the saved panel.

    BI = max(0, PFI(T,Rain,Hum) * pop_scale + eps).  Recover the implied
    noise eps_hat = BI - PFI*pop_scale, perturb one input holding eps fixed,
    and take the finite difference (this also captures zero-clipping).
    """
    pfi = panel['PFI'].values
    pop = panel['pop_density'].values
    bi = panel['BI'].values
    eps = bi - pfi * pop

    def eff(var, delta):
        T = panel['T'].values.copy()
        R = panel['Rain'].values.copy()
        H = panel['Hum'].values.copy()
        if var == 'Rain':
            R = R + delta
        else:
            T = T + delta
        pfi_p = base.compute_pfi_weekly(T, R, H)
        bi_p = np.maximum(0.0, pfi_p * pop + eps)
        return (bi_p - bi) / delta

    return eff('Rain', 1.0), eff('T', 0.1)


# ------------------------------------------------------------- DML core -----
def _xgb():
    from xgboost import XGBRegressor
    return XGBRegressor(n_estimators=300, learning_rate=0.05, max_depth=4,
                        subsample=0.8, colsample_bytree=0.8,
                        random_state=SEED, n_jobs=1)


def crossfit_residuals(Y, T, X, seed=SEED, k=K_FOLDS):
    """One cross-fitting split -> residualised outcome and treatment."""
    from sklearn.model_selection import KFold
    n = len(Y)
    folds = KFold(n_splits=k, shuffle=True, random_state=seed)
    g_hat = np.zeros(n)
    m_hat = np.zeros(n)
    for tr, te in folds.split(X):
        g_hat[te] = _xgb().fit(X[tr], Y[tr]).predict(X[te])
        m_hat[te] = _xgb().fit(X[tr], T[tr]).predict(X[te])
    return Y - g_hat, T - m_hat


def _theta_se(y_res, t_res, groups):
    n = len(y_res)
    denom = float(np.sum(t_res ** 2))
    theta = float(np.sum(t_res * y_res) / max(denom, 1e-12))
    psi = (t_res * y_res - theta * t_res ** 2) / max(denom / n, 1e-12)
    uniq = np.unique(groups)
    G = len(uniq)
    meat = sum(psi[groups == g].sum() ** 2 for g in uniq)
    var_cl = meat / n ** 2 * (G / (G - 1)) * ((n - 1) / max(n - 8, 1))
    var_hc = float(np.sum(psi ** 2) / n ** 2) * n / max(n - 8, 1)
    return theta, float(np.sqrt(max(var_cl, 0))), float(np.sqrt(max(var_hc, 0)))


def dml_ate(Y, T, X, groups, reps=N_SPLIT_REPS):
    """Linear-treatment DML, median over repeated random splits."""
    thetas, ses_cl, ses_hc = [], [], []
    for r in range(reps):
        y_res, t_res = crossfit_residuals(Y, T, X, seed=SEED + 101 * r)
        th, sc, sh = _theta_se(y_res, t_res, groups)
        thetas.append(th)
        ses_cl.append(sc)
        ses_hc.append(sh)
    i = int(np.argsort(thetas)[len(thetas) // 2])
    return float(np.median(thetas)), ses_cl[i], ses_hc[i], len(Y)


def naive_ols(Y, T):
    from sklearn.linear_model import LinearRegression
    return float(LinearRegression().fit(T.reshape(-1, 1), Y).coef_[0])


# ------------------------------------------------- spline dose-response ----
def spline_basis(t, knots):
    """Piecewise-linear (hat) basis: [t, max(0,t-k1), ...]."""
    cols = [t]
    for k_ in knots:
        cols.append(np.maximum(t - k_, 0.0))
    return np.column_stack(cols)


def dml_dose_curve(Y, T, X, groups, knots, grid_pts):
    """DML with a spline treatment basis (FWL): residualise Y and every
    basis column on X, then OLS of residualised Y on residualised basis.
    Returns the fitted response curve and cluster-robust pointwise SEs on
    `grid_pts`."""
    from sklearn.model_selection import KFold
    n = len(Y)
    B = spline_basis(T, knots)
    p = B.shape[1]
    y_res = np.zeros(n)
    B_res = np.zeros_like(B)
    folds = KFold(n_splits=K_FOLDS, shuffle=True, random_state=SEED)
    for tr, te in folds.split(X):
        y_res[te] = Y[te] - _xgb().fit(X[tr], Y[tr]).predict(X[te])
        for j in range(p):
            B_res[te, j] = B[te, j] - _xgb().fit(X[tr], B[tr, j]).predict(X[te])
    # final stage OLS without intercept (Frisch-Waugh-Lovell)
    XtX = B_res.T @ B_res
    XtX_inv = np.linalg.pinv(XtX)
    theta = XtX_inv @ B_res.T @ y_res
    eps = y_res - B_res @ theta
    # cluster-robust covariance of theta
    meat = np.zeros((p, p))
    for g in np.unique(groups):
        m = groups == g
        s = B_res[m].T @ eps[m]
        meat += np.outer(s, s)
    G = len(np.unique(groups))
    cov = XtX_inv @ meat @ XtX_inv * (G / (G - 1)) * ((n - 1) / max(n - p, 1))
    Bg = spline_basis(grid_pts, knots)
    curve = Bg @ theta
    se = np.sqrt(np.maximum(np.einsum('ij,jk,ik->i', Bg, cov, Bg), 0))
    return theta, curve, se


def truth_response_curve(panel, tvar, grid_pts):
    """Ground-truth dose-response: simulator partial dependence. Each
    observation's treatment is replaced by the grid value (all other inputs
    kept), the implied-noise-preserved BI is recomputed, and the mean over
    observations gives E[BI | do(T=t)] under the known mechanism."""
    pfi0 = panel['PFI'].values
    pop = panel['pop_density'].values
    bi = panel['BI'].values
    eps = bi - pfi0 * pop
    T0 = panel['T'].values.copy()
    R0 = panel['Rain'].values.copy()
    H0 = panel['Hum'].values.copy()
    out = []
    for gp in grid_pts:
        T, R = T0.copy(), R0.copy()
        if tvar == 'Rain':
            R = np.full_like(R, gp)
        else:
            T = np.full_like(T, gp)
        pfi = base.compute_pfi_weekly(T, R, H0)
        out.append(float(np.mean(np.maximum(0.0, pfi * pop + eps))))
    return np.array(out)


def truth_curve(panel, tvar, grid_pts, half_width):
    """Mean true marginal effect (derivative) within +/- half_width of each
    grid point — the ground-truth dose-response slope."""
    tr_r, tr_t = truth_marginal_effects(panel)
    truth = tr_r if tvar == 'Rain' else tr_t
    t = panel[tvar].values
    out = []
    for gp in grid_pts:
        m = np.abs(t - gp) <= half_width
        out.append(float(np.mean(truth[m])) if m.sum() > 30 else np.nan)
    return np.array(out)


# ------------------------------------------------------------- analysis -----
def build_analysis_frame(panel):
    df = panel.sort_values(['grid', 'week_idx']).reset_index(drop=True).copy()
    df['sin_week'] = np.sin(2 * np.pi * df['week_in_year'] / 52.0)
    df['cos_week'] = np.cos(2 * np.pi * df['week_in_year'] / 52.0)
    for var in ['Rain', 'T']:
        for lag in LAGS:
            df[f'{var}_lag{lag}'] = df.groupby('grid')[var].shift(lag)
    need = [f'{v}_lag{l}' for v in ['Rain', 'T'] for l in LAGS]
    return df.dropna(subset=need + ['BI']).reset_index(drop=True)


def confounders_for(df, tvar, lag):
    """Seasonality (sin/cos), spatial heterogeneity (pop_density), humidity,
    current-week weather (confounders for lagged treatments through weather
    autocorrelation) and the same-lag value of the other variable."""
    cols = ['sin_week', 'cos_week', 'pop_density', 'Hum', 'T', 'Rain']
    other = 'T' if tvar == 'Rain' else 'Rain'
    cols.append(f'{other}_lag{lag}')
    cols = [c for c in dict.fromkeys(cols) if c in df.columns]
    if f'{tvar}_lag{lag}' in cols:
        cols.remove(f'{tvar}_lag{lag}')
    return cols


def run_lag_curve(df, truth_rain, truth_t):
    rows = []
    groups = df['grid'].values
    Y = df['BI'].values.astype(float)
    for tvar, truth0 in [('Rain', truth_rain), ('T', truth_t)]:
        for lag in LAGS:
            tcol = f'{tvar}_lag{lag}'
            T = df[tcol].values.astype(float)
            X = df[confounders_for(df, tvar, lag)].values.astype(float)
            theta, se_cl, se_hc, n = dml_ate(Y, T, X, groups)
            naive = naive_ols(Y, T)
            true_val = float(np.mean(truth0)) if lag == 0 else 0.0
            # variance-weighted ground truth for the contemporaneous effect:
            # the estimand the linear DML actually targets (weights = squared
            # residualised treatment)
            wtruth = ''
            if lag == 0:
                _, t_res = crossfit_residuals(Y, T, X, seed=SEED)
                w = t_res ** 2
                wtruth = round(float(np.sum(w * truth0) / np.sum(w)), 4)
            lo, hi = theta - 1.96 * se_cl, theta + 1.96 * se_cl
            rows.append({'treatment': tvar, 'lag_weeks': lag,
                         'naive_ols': round(naive, 4),
                         'dml_ate': round(theta, 4),
                         'se_cluster': round(se_cl, 4),
                         'se_hc1': round(se_hc, 4),
                         'ci95_lo': round(lo, 4), 'ci95_hi': round(hi, 4),
                         'truth': round(true_val, 4),
                         'truth_weighted': wtruth,
                         'ci_covers_truth': int(lo <= true_val <= hi),
                         'n': n})
            print(f'  {tvar:4s} lag{lag}: DML={theta:7.4f} '
                  f'(95%CI {lo:7.4f},{hi:7.4f}) truth={true_val:7.4f} '
                  f'naive={naive:7.4f}', flush=True)
    return pd.DataFrame(rows)


def run_dose(df, panel):
    rows = []
    groups = df['grid'].values
    Y = df['BI'].values.astype(float)
    for tvar in ['Rain', 'T']:
        T = df[f'{tvar}_lag0'].values.astype(float)
        # data-adaptive knots and evaluation range (avoid data-sparse tails)
        qs = np.quantile(T, [0.01, 0.10, 0.25, 0.50, 0.75, 0.90, 0.99])
        knots = list(np.round(qs[1:-1], 1))
        grid_pts = np.linspace(qs[0], qs[-1], 41)
        hw = max((qs[-1] - qs[0]) / 40.0, 0.5)
        X = df[confounders_for(df, tvar, 0)].values.astype(float)
        theta, curve, se = dml_dose_curve(Y, T, X, groups, knots, grid_pts)
        dfit = np.gradient(curve, grid_pts)
        # naive spline (no confounder adjustment) for contrast
        B = spline_basis(T, knots)
        th_n = np.linalg.lstsq(np.column_stack([np.ones(len(T)), B]), Y,
                               rcond=None)[0]
        naive_curve = np.column_stack([np.ones(len(grid_pts)),
                                       spline_basis(grid_pts, knots)]) @ th_n
        # ground-truth response and slope; align levels at the median dose
        resp_truth = truth_response_curve(panel, tvar, grid_pts)
        ref = int(np.argmin(np.abs(grid_pts - np.median(T))))
        curve_al = curve - curve[ref]
        naive_al = naive_curve - naive_curve[ref]
        truth_al = resp_truth - resp_truth[ref]
        dtruth = truth_curve(panel, tvar, grid_pts, hw)
        for i, gp in enumerate(grid_pts):
            rows.append({'treatment': tvar, 'value': round(float(gp), 2),
                         'dml_response': round(float(curve_al[i]), 4),
                         'dml_se': round(float(se[i]), 4),
                         'naive_response': round(float(naive_al[i]), 4),
                         'truth_response': round(float(truth_al[i]), 4),
                         'dml_derivative': round(float(dfit[i]), 4),
                         'truth_derivative': (round(float(dtruth[i]), 4)
                                              if np.isfinite(dtruth[i]) else '')})
        print(f'  [dose] {tvar}: knots={knots}, range=({qs[0]:.1f},{qs[-1]:.1f})',
              flush=True)
    return pd.DataFrame(rows)


def main():
    print('loading panel and building analysis frame ...', flush=True)
    panel = pd.read_csv(os.path.join(BASELINE_DIR, 'results', 'panel_data.csv'))
    truth_rain, truth_t = truth_marginal_effects(panel)
    print(f'  ground truth: mean dBI/dRain(t)={truth_rain.mean():.4f} per mm; '
          f'mean dBI/dT(t)={truth_t.mean():.4f} per degC', flush=True)

    df = build_analysis_frame(panel)
    tru = panel[['grid', 'week_idx']].copy()
    tru['truth_rain'] = truth_rain
    tru['truth_t'] = truth_t
    df = df.merge(tru, on=['grid', 'week_idx'], how='left', validate='1:1')

    print('\n[DML] lag curves (repeated 5-fold cross-fitting, median)', flush=True)
    lag_res = run_lag_curve(df, df['truth_rain'].values, df['truth_t'].values)
    lag_res.to_csv(os.path.join(RES_A, 'dml_lag_effects.csv'), index=False)

    print('\n[DML] spline dose-response curves', flush=True)
    dose = run_dose(df, panel)
    dose.to_csv(os.path.join(RES_A, 'dml_dose_response.csv'), index=False)

    cov = lag_res['ci_covers_truth'].mean()
    print(f'\n95% CI coverage of ground truth (lag-curve estimates): {cov:.2f}')
    print(lag_res[lag_res['lag_weeks'] == 0]
          [['treatment', 'dml_ate', 'truth', 'se_cluster', 'se_hc1']]
          .to_string(index=False))
    print(f'\ndone. results -> {RES_A}', flush=True)


if __name__ == '__main__':
    main()
